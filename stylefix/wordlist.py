"""Conversion tables, generated from VarCon plus a few overrides.

Run ``python -m stylefix.wordlist`` to regenerate the Vale rules under
``stylefix/styles/ToUS`` and ``stylefix/styles/ToUK``:

- ToUS/Variants.yml   every VarCon spelling -> preferred American form
- ToUK/Variants.yml   conversions shared by -ise and Oxford British
- ToUK/Ise.yml        -ise-only conversions (organize -> organise); off under --oxford-ize
- ToUK/Oxford.yml     Oxford-only conversions (organise -> organize); on only under --oxford-ize
- To*/Ambiguous.yml   words whose target form depends on sense; adjudicated

Possessive forms (colour's) are omitted: the word-boundary match already
covers them.
"""

from __future__ import annotations

import re
from pathlib import Path

from . import candidates, patterns, varcon

STYLES_DIR = Path(__file__).parent / "styles"

# Pairs VarCon lacks or gets wrong for our purposes. (uk_form, us_form).
OVERRIDES_TO_US: dict[str, str] = {}
OVERRIDES_TO_UK: dict[str, str] = {}


def _clean(m: dict[str, str]) -> dict[str, str]:
    return {k: v for k, v in m.items() if "'" not in k and "'" not in v and " " not in k}


def to_us_map() -> dict[str, str]:
    """Every conversion, whether a pattern would find it or not."""
    return _clean(varcon.maps("us").convert) | OVERRIDES_TO_US


def to_uk_map(ise: bool = True) -> dict[str, str]:
    return _clean(varcon.maps("uk" if ise else "oxford").convert) | OVERRIDES_TO_UK


def _family(word: str, target: str, oxford: bool) -> str | None:
    for check, rx in patterns.VALE_TOKENS[target].items():
        if target == "uk" and check == ("PatIze" if oxford else "PatIse"):
            continue
        if re.fullmatch(rx.strip("\\b"), word):
            return patterns.CHECK_FAMILY[check]
    return None


def table_only(full: dict[str, str], target: str, oxford: bool = False) -> dict[str, str]:
    """The entries the pattern mechanism does not reproduce by itself.
    Vale's regex engine cannot take a 13,000-way alternation, and the
    patterns are dictionary-confirmed, so the table carries the rest:
    closed families, irregulars, and words the dictionaries let down."""
    out = {}
    for k, v in full.items():
        fam = _family(k, target, oxford)
        if fam:
            o = patterns.decide(k, fam, target, oxford)
            if o.status == "auto" and o.candidate.lower() == v.lower():
                continue
        out[k] = v
    return out


def ambiguous_words(target: str) -> set[str]:
    """Words that Ambiguous.yml must flag: VarCon's plus the hand-written ones."""
    words = set(candidates.TABLES[target])
    for t in (("us",) if target == "us" else ("uk", "oxford")):
        words |= {w for w in varcon.maps(t).ambiguous if "'" not in w and " " not in w}
    return words


def render_rule(message: str, swap: dict[str, str]) -> str:
    lines = [
        "# Generated by `python -m stylefix.wordlist`. Edit wordlist.py or the",
        "# VarCon data, not this file.",
        "extends: substitution",
        f"message: \"{message}\"",
        "level: error",
        "ignorecase: true",
        "action:",
        "  name: replace",
        "swap:",
    ]
    for k in sorted(swap):
        lines.append(f"  {k}: {swap[k]}")
    return "\n".join(lines) + "\n"


def render_ambiguous(target: str, words: set[str]) -> str:
    alts = "|".join(re.escape(w) for w in sorted(words, key=lambda w: (-len(w), w)))
    return (
        "# Generated by `python -m stylefix.wordlist`. Words whose "
        f"{target.upper()} form depends on sense; flag only, the adjudicator chooses.\n"
        "extends: existence\n"
        f"message: \"'%s' has more than one {target.upper()} spelling; needs adjudication.\"\n"
        "level: suggestion\nignorecase: true\ntokens:\n"
        f"  - '\\b({alts})\\b'\n")


CHUNK = 1500   # keys per substitution rule; Vale's regex engine backtracks


def _write_chunked(styles_dir: Path, style: str, name: str, message: str, swap: dict[str, str]) -> None:
    for old in (styles_dir / style).glob(f"{name}*.yml"):
        old.unlink()
    keys = sorted(swap)
    chunks = [keys[i:i + CHUNK] for i in range(0, len(keys), CHUNK)] or [[]]
    for i, ks in enumerate(chunks):
        suffix = "" if len(chunks) == 1 else str(i + 1)
        (styles_dir / style / f"{name}{suffix}.yml").write_text(
            render_rule(message, {k: swap[k] for k in ks}))


def write_styles(styles_dir: Path = STYLES_DIR) -> None:
    (styles_dir / "ToUS").mkdir(parents=True, exist_ok=True)
    (styles_dir / "ToUK").mkdir(parents=True, exist_ok=True)
    us = table_only(to_us_map(), "us")
    uk = table_only(to_uk_map(ise=True), "uk")
    ox = table_only(to_uk_map(ise=False), "uk", oxford=True)
    shared = {k: v for k, v in uk.items() if ox.get(k) == v}
    _write_chunked(styles_dir, "ToUS", "Variants", "Use US spelling '%s' instead of '%s'.", us)
    _write_chunked(styles_dir, "ToUK", "Variants", "Use UK spelling '%s' instead of '%s'.", shared)
    _write_chunked(styles_dir, "ToUK", "Ise", "Use UK -ise spelling '%s' instead of '%s'.",
                   {k: v for k, v in uk.items() if k not in shared})
    _write_chunked(styles_dir, "ToUK", "Oxford", "Use Oxford spelling '%s' instead of '%s'.",
                   {k: v for k, v in ox.items() if k not in shared})
    for target in ("us", "uk"):
        d = "ToUS" if target == "us" else "ToUK"
        (styles_dir / d / "Ambiguous.yml").write_text(render_ambiguous(target, ambiguous_words(target)))


if __name__ == "__main__":
    write_styles()
    from .patterns import write_vale_rules
    write_vale_rules(STYLES_DIR)
    print(f"wrote styles to {STYLES_DIR}: {len(to_us_map())} to-US ({len(table_only(to_us_map(), 'us'))} in table), "
          f"{len(to_uk_map())} to-UK ({len(table_only(to_uk_map(), 'uk'))} in table), "
          f"{len(to_uk_map(False))} to-Oxford ({len(table_only(to_uk_map(False), 'uk', True))} in table), "
          f"ambiguous us={len(ambiguous_words('us'))} uk={len(ambiguous_words('uk'))}")
